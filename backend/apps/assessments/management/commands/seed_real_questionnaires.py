def _set_questions(version, questions):
    """questions: список (code, indicator_code, text, [(label, value), ...]) по порядку с 1."""
    for order, (code, indicator_code, text, options) in enumerate(questions, start=1):
        question, created = Question.objects.get_or_create(
            questionnaire_version=version,
            order=order,
            defaults={"code": code, "text": text, "indicator_code": indicator_code},
        )
        if not created and (question.code, question.text, question.indicator_code) != (code, text, indicator_code):
            question.code, question.text, question.indicator_code = code, text, indicator_code
            question.save(update_fields=["code", "text", "indicator_code"])

        # Вопрос без вариантов (EQ-5D VAS) — options пуст, старые AnswerOption (если остались от
        # прежнего сидирования) подчищаем, чтобы фронтенд увидел свободный числовой ввод.
        question.options.exclude(order__in=range(1, len(options) + 1)).delete()
        for option_order, (label, value) in enumerate(options, start=1):
            AnswerOption.objects.update_or_create(
                question=question, order=option_order, defaults={"value": value, "label": label}
            )


class Command(BaseCommand):
    help = "Загружает реальные методики EQ-5D/HADS/Спилбергер-Ханина из файла методолога и делает их активным комплектом."

    @transaction.atomic
    def handle(self, *args, **options):
        eq5d_questions = [
            (code, indicator, text, [(label, value) for value, label in opts])
            for code, indicator, text, opts in EQ5D_DIMENSIONS
        ] + [("vas", "eq5d_vas", EQ5D_VAS_TEXT, [])]

        hads_questions = [
            (f"hads_{i}", indicator, text, options)
            for i, (indicator, text, options) in enumerate(HADS_QUESTIONS, start=1)
        ]

        stai_questions = [
            (f"stai_s{i}", "situational_anxiety", text, list(zip(SITUATIONAL_OPTIONS, key)))
            for i, (text, key) in enumerate(STAI_SITUATIONAL, start=1)
        ] + [
            (f"stai_t{i}", "trait_anxiety", text, list(zip(TRAIT_OPTIONS, key)))
            for i, (text, key) in enumerate(STAI_TRAIT, start=1)
        ]

        versions_by_code = {}
        for code, questions in (
            (QuestionnaireVersion.CODE_EQ5D, eq5d_questions),
            (QuestionnaireVersion.CODE_HADS, hads_questions),
            (QuestionnaireVersion.CODE_STAI, stai_questions),
        ):
            version, _ = QuestionnaireVersion.objects.get_or_create(
                code=code,
                version_label="prodex-v1",
                defaults={"is_active": True, "license_reference": "Методичка Vizion (оценка состояния), 2026"},
            )
            if not version.is_active:
                version.is_active = True
                version.save(update_fields=["is_active"])
            _set_questions(version, questions)
            versions_by_code[code] = version

        bundle, _ = TestBundle.objects.get_or_create(
            code="prodex-v1", defaults={"name": "EQ-5D + HADS + Спилбергер–Ханин", "is_active": True}
        )
        if not bundle.is_active:
            bundle.is_active = True
            bundle.save(update_fields=["is_active"])

        for order, code in enumerate(
            (QuestionnaireVersion.CODE_EQ5D, QuestionnaireVersion.CODE_HADS, QuestionnaireVersion.CODE_STAI), start=1
        ):
            TestBundleItem.objects.update_or_create(
                bundle=bundle, order=order, defaults={"questionnaire_version": versions_by_code[code]}
            )

        demo_organization = Organization.objects.filter(entry_code="demo-entry-code").first()
        if demo_organization is not None:
            demo_organization.test_bundles.add(bundle)

        deactivated_bundles = TestBundle.objects.exclude(pk=bundle.pk).filter(is_active=True).update(is_active=False)

        # apps/reporting/services.py::_eq5d_profile() ищет вопросы EQ-5D по "активная версия",
        # а не через комплект — если старая версия (например dummy-v0) тоже активна, её вопросы
        # задвоятся в профиле вместе с новыми. На один код методики активна ровно одна версия.
        deactivated_versions = (
            QuestionnaireVersion.objects.exclude(pk__in=[v.pk for v in versions_by_code.values()])
            .filter(is_active=True)
            .update(is_active=False)
        )

        self.stdout.write(
            self.style.SUCCESS(
                f"Комплект prodex-v1 активен (60 вопросов: 5 EQ-5D + 1 VAS + 14 HADS + 40 STAI). "
                f"Деактивировано других комплектов: {deactivated_bundles}, старых версий методик: {deactivated_versions}."
            )
        )
